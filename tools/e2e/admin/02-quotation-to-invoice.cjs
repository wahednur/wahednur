const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
const URL = 'http://localhost:5173';
(async () => {
  const b = await chromium.launch(process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : {});
  const p = await (await b.newContext({ viewport: { width: 1280, height: 1000 } })).newPage();
  p.on('pageerror', e => console.log('PAGEERROR', e.message));
  await p.goto(URL + '/login');
  await p.fill('input[name=email]', 'boss@example.com'); await p.fill('input[name=password]', 'a-very-long-pass-123'); await p.click('button[type=submit]');
  await p.waitForSelector('h1:has-text("Overview")', { timeout: 20000 });
  await p.click('nav >> text=Billing'); await p.click('button:has-text("New quotation")');
  await p.waitForSelector('h1:has-text("New quotation")');
  await p.selectOption('select >> nth=0', { index: 1 });
  await p.fill('input[maxlength="200"]', 'Online shop build');
  await p.selectOption('select >> nth=1', 'USD');
  await p.fill('input[aria-label=Description]', 'Storefront');
  await p.fill('input[aria-label="Unit price"]', '300');
  await p.click('button:has-text("Add line")');
  await p.locator('input[aria-label=Description]').nth(1).fill('Admin panel');
  await p.locator('input[aria-label=Quantity]').nth(1).fill('2');
  await p.locator('input[aria-label="Unit price"]').nth(1).fill('100');
  ok((await p.locator('body').innerText()).includes('Total $500.00'), 'live preview total is $500.00');
  await p.click('button:has-text("Create draft")');
  await p.waitForSelector('text=QUO-', { timeout: 15000 });
  ok((await p.locator('body').innerText()).includes('$500.00'), 'quotation saved; server total $500.00');
  await p.click('button:has-text("Send to client")'); await p.waitForSelector('button:has-text("Mark accepted")');
  await p.click('button:has-text("Mark accepted")'); await p.waitForSelector('button:has-text("Create invoice")');
  ok(true, 'sent, then accepted');
  await p.click('button:has-text("Create invoice")');
  await p.click('button:has-text("Start, middle, final")');
  ok((await p.locator('body').innerText()).includes('Adds up to $500.00 of $500.00'), 'plan preview adds up');
  await p.click('button:has-text("Create draft invoice")');
  await p.waitForSelector('text=INV-', { timeout: 15000 });
  const t = await p.locator('body').innerText();
  ok(t.includes('Start') && t.includes('$200.00') && t.includes('$150.00'), 'invoice has 40/30/30 installments ($200, $150, $150)');
  await p.click('button:has-text("Issue")'); await p.waitForSelector('text=Record a payment', { timeout: 15000 });
  ok(true, 'invoice issued');
  // a bad plan is refused by the server
  await p.goto(URL + '/billing/new/invoice'); await p.waitForSelector('h1:has-text("New invoice")');
  await p.selectOption('select >> nth=0', { index: 1 });
  await p.fill('input[maxlength="200"]', 'Bad plan'); await p.fill('input[aria-label=Description]', 'Work'); await p.fill('input[aria-label="Unit price"]', '100');
  await p.selectOption('select[aria-label="Percent or amount"]', 'amount'); await p.fill('input[aria-label=Value]', '60');
  await p.click('button:has-text("Create draft")'); await p.waitForSelector('[role=alert]', { timeout: 10000 });
  ok((await p.locator('[role=alert]').innerText()).includes('add up'), 'installments that do not add up are refused');
  await p.screenshot({ path: (process.env.E2E_TMP || '/tmp') + '/shot.png', fullPage: true });
  await b.close();
})().catch(e => { console.log('ERROR', e.message.split('\n').slice(0, 4).join(' | ')); process.exitCode = 1; });
